const dict: Record<Lang, Record<Keys, string>> = { en, "zh-TW": zhTW };

let current: Lang = "en";

export function detectLang(): Lang {
  try {
    const l = (window.localStorage.getItem("language") || "").toLowerCase();
    if (l.startsWith("zh")) return "zh-TW";
  } catch {
    /* ignore */
  }
  return "en";
}

export function setLang(l: Lang | "auto") {
  current = l === "auto" ? detectLang() : l;
}

export function t(key: Keys, vars?: Record<string, string | number>): string {
  let s = dict[current][key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}
